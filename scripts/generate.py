#!/usr/bin/env python3
"""Deterministic standard-library generator reading a Git revision of the public contract.

The contract is pinned by its contract_digest: the SHA-256 of the canonical JSON of the sorted
"module path -> SHA-256" map of the manifest modules. A different contract is refused.
"""
import argparse,hashlib,json,re,subprocess,pathlib
CONTRACT_DIGEST='371a499f74012bb6b41f23642869dee4954e8394dcba7642edc701aedb3dd59e'
ROOT=pathlib.Path(__file__).resolve().parents[1]
def snake(s):return re.sub(r'([a-z0-9])([A-Z])',r'\1_\2',re.sub(r'([A-Z]+)([A-Z][a-z])',r'\1_\2',s)).lower()
def camel(s):return ''.join(x[:1].upper()+x[1:] for x in re.split('[^A-Za-z0-9]+',s))
def run(source,check,revision='HEAD'):
 def get(p):return subprocess.check_output(['git','-C',str(source),'show',revision+':'+p])
 outputs={};models={};ops={};inputs=[];classes=[];methods={};docs=[]
 manifest=json.loads(get('contracts/manifest.json'))['contracts']
 digest=hashlib.sha256(json.dumps(dict(sorted((p,hashlib.sha256(get(p)).hexdigest()) for p in manifest)),separators=(',',':'),ensure_ascii=False).encode('utf-8')).hexdigest()
 if digest!=CONTRACT_DIGEST:raise SystemExit('Canonical contract_digest '+digest+' differs from the pinned '+CONTRACT_DIGEST)
 for path in manifest:
  raw=get(path);d=json.loads(raw);mod=path[10:].replace('.openapi.json','').replace('/','_').replace('-','_');ns=camel(mod);schemas=d['components']['schemas'];modelmap={}
  outputs['lib/Webmania/contracts/'+mod+'.json']=raw.decode('utf-8');inputs.append(dict(path=path,module=mod,sha256=hashlib.sha256(raw).hexdigest()))
  def shape(s,seen=frozenset()):
   props={}
   if '$ref' in s:
    key=s['$ref'].split('/')[-1]
    if key not in seen:props.update(shape(schemas[key],seen|{key}))
   props.update(s.get('properties',{}))
   for k in ['allOf','anyOf','oneOf']:
    for c in s.get(k,[]):props.update(shape(c,seen))
   return props
  def register(s,name):
   if not isinstance(s,dict):return
   if '$ref' in s and len(s)==1:return
   props=shape(s)
   if props or s.get('type')=='object':
    if name in modelmap:return
    modelmap[name]={'schema':s,'fields':list(props)}
    for k,v in props.items():register(v,name+camel(k))
   if s.get('type')=='array':register(s.get('items',{}),name+'Item')
   for k in ['anyOf','oneOf','allOf']:
    for i,c in enumerate(s.get(k,[])):register(c,name+'Variant'+str(i))
  for name,s in schemas.items():register(s,name)
  for route,item in d['paths'].items():
   for verb,spec in item.items():
    if not isinstance(spec,dict) or 'operationId' not in spec:continue
    oid=spec['operationId']
    if mod=='api1_fiscal':scope,method='Nfe',re.sub('^(nfe|fiscal)','',oid)
    elif mod=='api1_b2b':scope,method='Reseller',oid.removeprefix('b2bV1')
    elif mod=='api1_files':scope,method='NfeFiles',re.sub('^(nfe|fiscal)','',oid)
    elif mod=='api2_emitter_files':scope,method='EmitterFiles',oid.removeprefix('file')
    elif mod=='api2_reports':scope,method='ReportFiles',re.sub('^(nfe|fiscal)','',oid)
    elif mod.startswith('api2_monitor'):scope,method='Monitor',oid.removeprefix('monitor')
    else:scope,method='Emitter',oid.removeprefix('emitter')
    method=snake(method);params=item.get('parameters',[])+spec.get('parameters',[])
    q={'type':'object','properties':{p['name']:p['schema'] for p in params if p['in']=='query'},'required':[p['name'] for p in params if p['in']=='query' and p.get('required')],'additionalProperties':False}
    register(q,camel(oid)+'Query');body=spec.get('requestBody',{}).get('content',{}).get('application/json',{}).get('schema')
    if body is not None:register(body,camel(oid)+'Body')
    for status,r in spec['responses'].items():
     if status.startswith('2'):
      for media,c in r.get('content',{}).items():
       if media=='application/json':register(c['schema'],camel(oid)+'Response'+status)
    ops[oid]=dict(module=mod,scope=scope,method=method,verb=verb.upper(),path=route,parameters=params,query_schema=q,spec=spec)
    methods.setdefault(scope,[]).append(f"sub {method} {{ my ($self, %args) = @_; return $self->_execute('{oid}', \\%args); }}")
    docs.append(f"| `{scope}Client->{method}` | `{oid}` | {'blocked' if spec.get('x-sdk-generation-enabled') is False else 'enabled'} |")
  for name,meta in modelmap.items():
   classname='Webmania::Models::'+ns+'::'+name
   models[classname]=dict(module=mod,primary=2 if name in schemas else 1 if any(name.startswith(key) for key in schemas) else 0,**meta);classes.append(f"package {classname}; our @ISA = ('Webmania::Model');")
  for name,s in schemas.items():
   classname='Webmania::Models::'+ns+'::'+name
   if classname not in models:
    models[classname]=dict(module=mod,schema=s,fields=[],scalar=True,primary=2);classes.append(f"package {classname}; our @ISA = ('Webmania::Scalar');")
 outputs['lib/Webmania/Generated.pm']='# Generated by scripts/generate.py; do not edit.\nuse strict; use warnings;\n'+'\n'.join(classes)+'\n'+ '\n'.join('package Webmania::'+s+'Client;\n'+'\n'.join(ms) for s,ms in methods.items())+'\n1;\n'
 outputs['lib/Webmania/contracts/models.json']=json.dumps(models,ensure_ascii=False,separators=(',',':'))+'\n'
 outputs['lib/Webmania/contracts/operations.json']=json.dumps(ops,ensure_ascii=False,separators=(',',':'))+'\n'
 outputs['docs/operations.md']='# Generated operation coverage\n\n| Perl facade | Pinned operation | Gate |\n| --- | --- | --- |\n'+'\n'.join(docs)+'\n'
 outputs['contracts.lock.json']=json.dumps(dict(generator='scripts/generate.py',contract_digest=digest,modules=len(inputs),operations=len(ops),enabled_operations=sum(o['spec'].get('x-sdk-generation-enabled') is not False for o in ops.values()),object_models=sum(not x.get('scalar') for x in models.values()),scalar_models=sum(bool(x.get('scalar')) for x in models.values()),inputs=inputs),indent=2)+'\n'
 for target,text in outputs.items():
  p=ROOT/target
  data=text.encode('utf-8')
  if check:
   if not p.exists() or p.read_bytes()!=data:raise SystemExit('Generated output differs: '+target)
  else:p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes(data)
 print(json.dumps(dict(operations=len(ops),models=len(models),check=check)))
if __name__=='__main__':
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--source',type=pathlib.Path,required=True,help='webmania-openapi Git checkout');p.add_argument('--revision',default='HEAD',help='Git revision of the checkout to read (default HEAD)');p.add_argument('--check',action='store_true');a=p.parse_args();run(a.source,a.check,a.revision)
